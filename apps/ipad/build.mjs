// Builds the web folder the iPad app carries: the UI (packages/ui/dist), the host script that
// runs the backend in the page (src/main.ts, bundled for the browser with Node's modules
// replaced by src/shims), the library seed, and the thesaurus. The result is copied into the
// Swift package ("Folio Dome.swiftpm/Resources/web"), where Xcode and Swift Playgrounds find it.
import { build } from 'esbuild';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const web = join(here, 'dist', 'web');
const shims = join(here, 'src', 'shims');

await rm(web, { recursive: true, force: true });
await mkdir(web, { recursive: true });

const uiDist = join(root, 'packages', 'ui', 'dist');
if (!existsSync(uiDist)) throw new Error('UI not built: run `npm run build -w @mde/ui` first.');
await cp(uiDist, join(web, 'renderer'), { recursive: true, filter: (src) => !src.endsWith('.map') });

await build({
  entryPoints: [join(here, 'src', 'main.ts')],
  outfile: join(web, 'renderer', 'ipad-host.js'),
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['safari17'],
  minify: true,
  sourcemap: false,
  legalComments: 'external',
  logLevel: 'warning',
  alias: {
    'node:fs': join(shims, 'fs.ts'),
    'node:path': join(shims, 'path.ts'),
    'node:os': join(shims, 'os.ts'),
    'node:crypto': join(shims, 'crypto.ts'),
  },
  // pdf.js loads Node modules only when it runs in Node; in the page those imports are never reached.
  external: ['node:*', 'fs', 'path', 'url', 'canvas', 'module'],
  define: { 'process.env.NODE_ENV': '"production"' },
});

// The host script runs before the UI's module script, so window.mdeHost exists when the UI starts.
const indexPath = join(web, 'renderer', 'index.html');
const index = await readFile(indexPath, 'utf8');
if (!index.includes('<script type="module"')) throw new Error('index.html has no module script to put the host before.');
await writeFile(indexPath, index.replace('<script type="module"', '<script src="./ipad-host.js"></script>\n    <script type="module"'));

await cp(join(root, 'resources', 'seed'), join(web, 'seed'), { recursive: true });
// Themes kept out of the repository (resources/private/Themes, git-ignored) come with builds made on this machine.
const privateThemes = join(root, 'resources', 'private', 'Themes');
if (existsSync(privateThemes) && process.env.FOLIO_PRIVATE_THEMES !== '0') await cp(privateThemes, join(web, 'seed', 'Themes'), { recursive: true });

const thesaurusScript = join(root, 'scripts', 'build-thesaurus.mjs');
const cache = join(root, 'node_modules', '.cache', 'mde-thesaurus');
const cached = join(cache, 'en.thes');
if (!existsSync(cached) || statSync(cached).mtimeMs < statSync(thesaurusScript).mtimeMs) execFileSync(process.execPath, [thesaurusScript, cached], { stdio: 'inherit' });
await cp(cache, join(web, 'thesaurus'), { recursive: true });

const version = JSON.parse(await readFile(join(here, 'package.json'), 'utf8')).version;
await writeFile(join(web, 'version.json'), `${JSON.stringify({ version }, null, 2)}\n`);

// The menu bar comes from the same menus as the Mac app's (packages/core/src/menus.ts).
const menusModule = await build({ entryPoints: [join(root, 'packages', 'core', 'src', 'menus.ts')], bundle: true, format: 'esm', platform: 'neutral', write: false, logLevel: 'warning' });
const { APP_MENUS } = await import(`data:text/javascript;base64,${Buffer.from(menusModule.outputFiles[0].text).toString('base64')}`);
await writeFile(join(here, 'Folio Dome.swiftpm', 'Sources', 'MenuSpec.swift'), menuSpec(APP_MENUS));

/** Swift lists of the menus' commands, with separators between groups (the shell supplies the standard items). */
function menuSpec(menus) {
  const quote = (s) => JSON.stringify(s);
  const lists = menus.map((section) => {
    const items = [];
    for (const item of section.items) {
      if ('command' in item) items.push(`.init(label: ${quote(item.label)}, command: ${quote(item.command)})`);
      else if ('separator' in item && items.length && items[items.length - 1] !== 'sep') items.push('sep');
    }
    while (items[items.length - 1] === 'sep') items.pop();
    const name = section.role === 'appMenu' ? 'app' : section.label.toLowerCase();
    return `    static let ${name}: [Item] = [\n${items.map((i) => `        ${i === 'sep' ? '.separator' : i},`).join('\n')}\n    ]`;
  });
  return `// Generated by apps/ipad/build.mjs from packages/core/src/menus.ts. Do not edit.

enum MenuSpec {
    struct Item {
        let label: String
        /** nil for a separator. */
        let command: String?

        init(label: String, command: String) {
            self.label = label
            self.command = command
        }

        private init() {
            label = ""
            command = nil
        }

        static let separator = Item()
    }

${lists.join('\n\n')}
}
`;
}

// The app package and the Xcode project show the same version as the web folder.
for (const [file, pattern, replacement] of [
  [join(here, 'Folio Dome.swiftpm', 'Package.swift'), /displayVersion: "[^"]*"/, `displayVersion: "${version}"`],
  [join(here, 'xcode', 'project.yml'), /MARKETING_VERSION: "[^"]*"/, `MARKETING_VERSION: "${version}"`],
]) {
  const text = await readFile(file, 'utf8');
  if (!pattern.test(text)) throw new Error(`No version to update in ${file}`);
  await writeFile(file, text.replace(pattern, replacement));
}

const resources = join(here, 'Folio Dome.swiftpm', 'Resources', 'web');
await rm(resources, { recursive: true, force: true });
await cp(web, resources, { recursive: true });
console.log('Built apps/ipad/dist/web and copied it into Folio Dome.swiftpm/Resources/web');
